import assert from 'node:assert/strict';
import {mapLocation,eventMap} from './map-locations.mjs';
const supplied='https://maps.app.goo.gl/HvYR4E3dMQeP8DkZA?';
const actual=mapLocation(supplied);
assert.deepEqual(actual.pin,[1.4262216,124.9857088]);
assert.equal(new URL(actual.embed).searchParams.get('q'),'1.4262216,124.9857088');
assert.equal(new URL(actual.link).pathname,'/HvYR4E3dMQeP8DkZA');
assert.deepEqual(mapLocation('https://www.google.com/maps?q=1.4262216,124.9857088').pin,actual.pin);
assert.deepEqual(mapLocation('https://www.google.com/maps/search/?api=1&query=-6.2%2C106.8').pin,[-6.2,106.8]);
assert.deepEqual(mapLocation('https://www.google.com/maps/place/Test/@0,0,10z/data=!3d1.42!4d124.98').pin,[1.42,124.98]);
assert.equal(mapLocation('https://www.google.com/maps/place/Test/@0,0,10z').embed,'');
assert.equal(mapLocation('https://www.google.com/maps?q=Rumah+Adik+Joel').embed,'');
assert.equal(mapLocation('https://maps.app.goo.gl/OTHER').embed,'');
assert.equal(mapLocation('https://maps.app.goo.gl/OTHER').link,'https://maps.app.goo.gl/OTHER');
for(const url of ['javascript:alert(1)','https://evil.test/maps?q=1,2','https://user:secret@www.google.com/maps?q=1,2','http://maps.google.com/?q=1,2'])assert.equal(mapLocation(url).link,'');
for(const q of ['91,2','1,181','abc,2'])assert.equal(mapLocation('https://www.google.com/maps?q='+q).embed,'');
const content={ceremonyVenue:'Church',ceremonyAddress:'An address',ceremonyMapsUrl:'',receptionMapsUrl:supplied,mapsUrl:supplied};
assert.equal(eventMap(content,'ceremony').link,'');
assert.deepEqual(eventMap(content,'reception').pin,actual.pin);
console.log('PASS: supplied short link and pin agree; viewport/name searches are not used as pins; events stay separate; unknown links remain clickable; invalid URLs rejected.');
